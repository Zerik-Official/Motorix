"""Generic repository with the data access shared by every model."""

# Standard library
from __future__ import annotations
from collections.abc import Sequence
from typing import Any, Generic, TypeVar
from uuid import UUID

# Third-party
from sqlalchemy import ColumnElement, Select, func, select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm.interfaces import ORMOption

# Project imports
from app.db.base import Base

ModelT = TypeVar("ModelT", bound=Base)


class BaseRepository(Generic[ModelT]):
    """Reads and writes one model; subclasses add the queries specific to it."""

    model: type[ModelT]

    def __init__(self, session: AsyncSession) -> None:
        """
        Bind the repository to the session of the current unit of work.

        Args:
            session: Open async session.
        """
        self._session: AsyncSession = session

    async def get(self, entity_id: UUID, options: Sequence[ORMOption] = ()) -> ModelT | None:
        """
        Fetch one row by primary key.

        Args:
            entity_id: Primary key.
            options: Loader options, such as `selectinload`, to fetch relations in the same round trip.

        Returns:
            The row, or None when it does not exist.
        """
        statement: Select[tuple[ModelT]] = select(self.model).where(self._primary_key() == entity_id)
        if options:
            statement = statement.options(*options)
        return (await self._session.execute(statement)).scalars().first()

    async def list(
        self,
        offset: int,
        limit: int,
        filters: Sequence[ColumnElement[bool]] = (),
        order_by: Sequence[Any] = (),
        options: Sequence[ORMOption] = (),
    ) -> Sequence[ModelT]:
        """
        Fetch one page of rows.

        Args:
            offset: Rows skipped.
            limit: Maximum rows returned.
            filters: Conditions combined with AND.
            order_by: Sort expressions; the primary key is always appended to keep pages stable.
            options: Loader options to fetch relations without N+1 queries.

        Returns:
            The rows of the page.
        """
        statement: Select[tuple[ModelT]] = (
            select(self.model)
            .where(*filters)
            .order_by(*order_by, self._primary_key())
            .offset(offset)
            .limit(limit)
        )
        if options:
            statement = statement.options(*options)
        return (await self._session.execute(statement)).scalars().all()

    async def count(self, filters: Sequence[ColumnElement[bool]] = ()) -> int:
        """
        Count the rows matching the filters.

        Args:
            filters: Conditions combined with AND.

        Returns:
            The number of rows.
        """
        statement: Select[tuple[int]] = select(func.count()).select_from(self.model).where(*filters)
        return int((await self._session.execute(statement)).scalar_one())

    async def exists(self, filters: Sequence[ColumnElement[bool]]) -> bool:
        """
        Tell whether at least one row matches the filters.

        Args:
            filters: Conditions combined with AND.

        Returns:
            True when a row matches.
        """
        statement: Select[tuple[bool]] = select(select(self.model).where(*filters).exists())
        return bool((await self._session.execute(statement)).scalar_one())

    async def add(self, entity: ModelT) -> ModelT:
        """
        Insert a row and load the values generated by the database.

        Args:
            entity: New row.

        Returns:
            The persisted row.
        """
        self._session.add(entity)
        await self._session.flush()
        await self._session.refresh(entity)
        return entity

    async def save(self, entity: ModelT) -> ModelT:
        """
        Flush the changes of a loaded row and load the values generated by the database.

        Args:
            entity: Modified row.

        Returns:
            The updated row.
        """
        await self._session.flush()
        await self._session.refresh(entity)
        return entity

    def _primary_key(self) -> Any:
        """
        Return the primary key column of the model.

        Returns:
            The `id` column.
        """
        return getattr(self.model, "id")
